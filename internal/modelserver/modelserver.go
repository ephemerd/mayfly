// Package modelserver renders the guest-side setup for the fleet's model
// server: an Ubuntu VM holding a passed-through NVIDIA GPU, running Ollama so
// ephemerd can reach an OpenAI-compatible API on the LAN.
//
// Boot order matters, and the scripts below exist to enforce it:
//
//  1. mayfly-gpu-setup installs the NVIDIA driver from Ubuntu's archive,
//     pinned to the 580 branch. 580 is the LAST branch that supports Pascal
//     (the Tesla P40); later branches dropped Maxwell, Pascal and Volta, so an
//     unpinned "latest" driver would install fine and then see no GPU.
//  2. Ollama installs after the driver. Its installer looks for nvidia-smi
//     and, when it is missing on a machine with an NVIDIA card, installs
//     NVIDIA's newest CUDA driver itself — exactly the unpinned driver step 1
//     avoids. Installing the driver first makes the installer leave it alone.
//  3. Models are pulled by a separate oneshot unit started without blocking,
//     so a multi-GB download never holds cloud-init (or `mayfly apply`) up.
//     It is enabled, so a pull interrupted by a reboot simply resumes.
//
// If the kernel module cannot load in place (a console driver already holds
// the card), mayfly-gpu-setup blacklists nouveau and the VM reboots once at
// the end of cloud-init; Ollama and the pull unit come up on their own after.
package modelserver

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"strings"
)

const (
	// DriverBranch is the pinned NVIDIA driver branch. See the package comment.
	DriverBranch = "580"

	GPUSetupPath = "/usr/local/sbin/mayfly-gpu-setup"
	PullPath     = "/usr/local/sbin/mayfly-model-pull"
	// HealthPath succeeds only when the GPU is usable AND Ollama answers;
	// run it with `mayfly node exec model-server`.
	HealthPath = "/usr/local/sbin/mayfly-model-health"
	EnvPath    = "/etc/mayfly/model-server.env"
	// OllamaDropIn overrides the unit the Ollama installer writes, so the
	// listen address survives an Ollama reinstall/upgrade.
	OllamaDropIn = "/etc/systemd/system/ollama.service.d/mayfly.conf"
	PullUnitPath = "/etc/systemd/system/" + PullUnit
	PullUnit     = "mayfly-model-pull.service"
	// RebootFlag is touched by mayfly-gpu-setup when the driver needs a
	// reboot to bind the card.
	RebootFlag = "/run/mayfly-reboot-required"
)

// File is one rendered guest file.
type File struct {
	Path    string
	Mode    string // octal string, e.g. "0644"
	Content []byte
}

// Spec is what the guest files are rendered from.
type Spec struct {
	Port   int
	Models []string
}

// Files renders every guest file for spec.
func Files(spec Spec) []File {
	return []File{
		{Path: EnvPath, Mode: "0644", Content: []byte(envFile(spec))},
		{Path: GPUSetupPath, Mode: "0755", Content: []byte(gpuSetup)},
		{Path: OllamaDropIn, Mode: "0644", Content: []byte(ollamaDropIn(spec.Port))},
		{Path: PullPath, Mode: "0755", Content: []byte(pullScript)},
		{Path: PullUnitPath, Mode: "0644", Content: []byte(pullUnit)},
		{Path: HealthPath, Mode: "0755", Content: []byte(healthScript)},
	}
}

// Dirs are the guest directories the files land in. The create path gets
// them from cloud-init's write_files; the in-place update path writes files
// through the guest agent, which does not create parents.
func Dirs() []string {
	return []string{"/etc/mayfly", "/etc/systemd/system/ollama.service.d"}
}

// Hash fingerprints the rendered files, so a change to any script or to the
// spec shows up as a config push in the plan.
func Hash(spec Spec) string {
	h := sha256.New()
	for _, f := range Files(spec) {
		fmt.Fprintf(h, "%s %s %d\n", f.Path, f.Mode, len(f.Content))
		h.Write(f.Content)
	}
	return hex.EncodeToString(h.Sum(nil))[:16]
}

// FirstBootCommands is the cloud-init runcmd that brings the server up, in
// the order the package comment explains.
func FirstBootCommands() []string {
	return []string{
		GPUSetupPath,
		// The installer creates the ollama user and unit, and finds the driver
		// installed above.
		"curl -fsSL https://ollama.com/install.sh | sh",
		"systemctl daemon-reload",
		"systemctl enable ollama",
		"systemctl restart ollama",
		"systemctl enable " + PullUnit,
		"systemctl start --no-block " + PullUnit,
		"if [ -f " + RebootFlag + " ]; then systemctl reboot; fi",
	}
}

// ReconcileCommand re-applies pushed files on a running server: reload units,
// restart Ollama onto the new drop-in, and pull whatever models are now
// listed. The driver and Ollama are not reinstalled.
func ReconcileCommand() []string {
	return []string{"/bin/sh", "-c",
		"systemctl daemon-reload && systemctl restart ollama && systemctl enable " + PullUnit +
			" && systemctl restart --no-block " + PullUnit}
}

func envFile(spec Spec) string {
	return fmt.Sprintf(`# Generated by mayfly. Do NOT edit — rewritten on every apply.
MODEL_SERVER_PORT=%d
MODEL_SERVER_MODELS="%s"
`, spec.Port, strings.Join(spec.Models, " "))
}

func ollamaDropIn(port int) string {
	return fmt.Sprintf(`# Generated by mayfly. Do NOT edit — rewritten on every apply.
[Service]
# Listen on every interface, not Ollama's loopback default: the clients are
# ephemerd daemons on the runner nodes.
Environment="OLLAMA_HOST=0.0.0.0:%d"
# Keep a loaded model resident; reloading a model from disk into VRAM is the
# slow part of a request.
Environment="OLLAMA_KEEP_ALIVE=24h"
`, port)
}

const gpuSetup = `#!/bin/sh
# Generated by mayfly. Installs the pinned NVIDIA driver and makes sure it
# drives the passed-through GPU. See internal/modelserver for the why.
set -eu
BRANCH=` + DriverBranch + `

export DEBIAN_FRONTEND=noninteractive
apt-get update
# Headers for the running kernel: the driver's kernel module is built by DKMS
# against them, whichever kernel flavor the cloud image ships.
apt-get install -y --no-install-recommends "linux-headers-$(uname -r)"
apt-get install -y --no-install-recommends \
  "nvidia-headless-${BRANCH}-server" "nvidia-utils-${BRANCH}-server"

if modprobe nvidia 2>/dev/null && nvidia-smi >/dev/null 2>&1; then
  echo "mayfly-gpu-setup: driver ${BRANCH} loaded"
  nvidia-smi -L
  exit 0
fi

# The module would not load in place, almost always because nouveau already
# holds the card. Keep nouveau off it from now on and reboot once.
echo "mayfly-gpu-setup: driver installed but not bound; blacklisting nouveau and rebooting"
cat >/etc/modprobe.d/mayfly-blacklist-nouveau.conf <<'EOF'
blacklist nouveau
options nouveau modeset=0
EOF
update-initramfs -u
touch ` + RebootFlag + `
`

const pullScript = `#!/bin/sh
# Generated by mayfly. Pulls every configured model. Safe to re-run: Ollama
# skips layers it already has.
set -eu
. ` + EnvPath + `
# Wait for the server: on first boot it is starting while this runs.
i=0
until ollama list >/dev/null 2>&1; do
  i=$((i + 1))
  [ "$i" -ge 60 ] && { echo "mayfly-model-pull: ollama never answered"; exit 1; }
  sleep 5
done
for m in $MODEL_SERVER_MODELS; do
  echo "mayfly-model-pull: pulling $m"
  ollama pull "$m"
done
`

const pullUnit = `# Generated by mayfly. Do NOT edit — rewritten on every apply.
[Unit]
Description=Pull the model server's configured models
After=ollama.service network-online.target
Wants=network-online.target
Requires=ollama.service

[Service]
Type=oneshot
Environment=HOME=/root
ExecStart=` + PullPath + `
# A pull over a flaky WAN fails partway; try again rather than leave the
# server without its model.
Restart=on-failure
RestartSec=60

[Install]
WantedBy=multi-user.target
`

const healthScript = `#!/bin/sh
# Generated by mayfly. Exit 0 only when the GPU is usable and Ollama answers.
set -u
. ` + EnvPath + `
if ! nvidia-smi -L; then
  echo "mayfly-model-health: no usable GPU (nvidia-smi failed)"
  exit 1
fi
if ! curl -fsS -o /dev/null "http://127.0.0.1:${MODEL_SERVER_PORT}/api/tags"; then
  echo "mayfly-model-health: ollama is not answering on :${MODEL_SERVER_PORT}"
  exit 1
fi
echo "mayfly-model-health: ok"
ollama list
`
